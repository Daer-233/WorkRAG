def main():
    OUT.mkdir(parents=True,exist_ok=True)
    source={'entry_id':'00000000-0000-4000-8000-000000000001','title':'测试用资料A','available':True}
    for split,groups in DATA.items():
        rows=[]
        for label,texts in groups.items():
            for number,text in enumerate(texts,1):
                row={'id':f'{split}-{label}-{number:02}','family':f'{split}-{label}-{number:02}',
                     'source_type':'curated_work_scenario','reviewed_by':'agent','human_review':'pending',
                     'intent':label,'text':text,'tags':['clear'] if label!='clarify' else ['boundary']}
                if split=='calibration' and label=='clarify' and number in (5,6):row['attachment_types']=['image']
                if split=='acceptance':
                    if label=='knowledge' and number in (1,13,14,15,18,19,20):row['tags']=['boundary','mixed']
                    if label=='daily' and number in (1,2,5,9,17):row['tags']=['boundary']
                    if label=='images' and number>=13:row['tags']=['boundary']
                    if label=='source_file' and number>=18:
                        row.update(previous_file_offer=True,previous_sources=[source],history=[{'role':'assistant','text':'依据《测试用资料A》，需要源文件吗？'}],tags=['boundary','multi_turn'])
                    if label=='clarify' and number in (1,4,12,13,18):row['attachment_types']=['image']
                    if label=='clarify' and number==17:
                        row.update(previous_file_offer=True,previous_sources=[source,dict(source,entry_id='00000000-0000-4000-8000-000000000002',title='测试用资料B')],history=[{'role':'assistant','text':'两份资料都有关，需要源文件吗？'}],tags=['boundary','multi_turn'])
                rows.append(row)
        assert len(rows)=={'index':80,'calibration':60,'acceptance':100}[split]
        (OUT/(split+'.jsonl')).write_text(''.join(json.dumps(r,ensure_ascii=False)+'\n' for r in rows),encoding='utf-8')
    print('Created 80 index / 60 calibration / 100 acceptance curated cases. Human business review pending.')


if __name__=='__main__':main()
